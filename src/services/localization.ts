export function translate(locale: Locale, message: string, values?: Record<string, string | number>): string {
  let translated = locale === 'en' ? englishMessages[message] ?? message : message;
  if (locale === 'en' && translated === message) {
    const errorPrefixes: Record<string, string> = {
      'Não foi possível carregar o perfil da extensão:': 'Could not load the extension profile:',
      'Não foi possível carregar o perfil local:': 'Could not load the local profile:',
      'Não foi possível salvar o perfil da extensão:': 'Could not save the extension profile:',
      'Não foi possível salvar o perfil local:': 'Could not save the local profile:',
      'Não foi possível salvar as respostas:': 'Could not save the answers:',
    };
    const prefix = Object.keys(errorPrefixes).find((candidate) => message.startsWith(candidate));
    if (prefix) translated = `${errorPrefixes[prefix]}${message.slice(prefix.length)}`;
  }
  return values
    ? Object.entries(values).reduce((result, [key, value]) => result.split(`{${key}}`).join(String(value)), translated)
    : translated;
}

export function translatePlural(locale: Locale, singular: string, plural: string, count: number): string {
  return translate(locale, count === 1 ? singular : plural, { count });
}

export function getBrowserLocale(): Locale {
  return typeof navigator !== 'undefined' && navigator.language.toLowerCase().startsWith('pt')
    ? 'pt-BR'
    : 'en';
}

export async function loadPreferredLocale(): Promise<Locale | null> {
  if (typeof chrome !== 'undefined' && chrome.storage?.local) {
    try {
      const stored = await chrome.storage.local.get(LOCALE_STORAGE_KEY);
      return stored[LOCALE_STORAGE_KEY] === 'en' || stored[LOCALE_STORAGE_KEY] === 'pt-BR'
        ? stored[LOCALE_STORAGE_KEY]
        : null;
    } catch {
      return null;
    }
  }

  try {
    const stored = window.localStorage.getItem(LOCALE_STORAGE_KEY);
    return stored === 'en' || stored === 'pt-BR' ? stored : null;
  } catch {
    return null;
  }
}

export async function savePreferredLocale(locale: Locale): Promise<void> {
  if (typeof chrome !== 'undefined' && chrome.storage?.local) {
    await chrome.storage.local.set({ [LOCALE_STORAGE_KEY]: locale });
    return;
  }

  window.localStorage.setItem(LOCALE_STORAGE_KEY, locale);
}
